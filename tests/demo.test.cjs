'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),saved=new Map(),window={};
const storage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,String(v)),removeItem:k=>saved.delete(k)};
const context=vm.createContext({window,Date,console,sessionStorage:storage});
for(const f of ['data/competencies.js','data/procedures.js','data/first-rules.js','data/demo-scenarios.js','data/knowledge.js','js/assessment.js','js/validation.js','js/workflow.js','js/session.js','js/engine.js','js/state.js','js/demo.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),context,{filename:f});
const S=window.KOMPAS_STORE,D=window.KOMPAS_DEMO,F=window.KOMPAS_FIRST_RULES,W=window.KOMPAS_WORKFLOW;
let checks=0;function ok(condition,msg){assert.ok(condition,msg);checks++;}
let original=S.initial();original.case.employee='Praca użytkownika';original.meeting.questions='Moje pytania';original.observations['komunikacja:0']={level:4,note:'Notatki użytkownika'};
S.save(original);
const first=D.begin('first-positive',original,storage);
ok(first.ok,'positive fixture loaded');ok(D.current(first.state).id==='first-positive','active scenario marker');
ok(F.evaluate(first.state.firstFormal).result==='pozytywna','positive calculated by unchanged rules');
ok(W.canNavigate(first.state,5).ok,'positive scenario navigable');
ok(D.get('first-positive').expected.includes('§ 10'),'expected result description');
S.save(first.state);
const neg=D.begin('first-negative',first.state,storage);
ok(neg.ok,'switch scenario');ok(F.evaluate(neg.state.firstFormal).result==='negatywna','negative calculated by unchanged rules');
ok(!W.canNavigate(neg.state,5).ok,'missing negative reason blocks');
neg.state.firstFormal.negativeReason='Uzasadnienie co najmniej osiem znaków';
ok(W.canNavigate(neg.state,5).ok,'adding negative reason allows navigation');
const missing=D.begin('missing-fields',neg.state,storage);
ok(missing.ok,'missing fields fixture');ok(!W.canNavigate(missing.state,1).ok,'engine validation blocks');
const periodic=D.begin('periodic-demo',missing.state,storage);
ok(periodic.ok&&periodic.state.case.track==='periodic','periodic fixture loaded');ok(W.canNavigate(periodic.state,5).ok,'periodic full demo still navigates');
const ai=D.begin('assistant-sources',periodic.state,storage);
ok(ai.ok&&ai.state.assistant.mode==='offline','AI scenario source-only by default');
ok(D.current(ai.state).questions.length===3,'AI suggested questions');
ok(!D.begin('unknown',ai.state,storage).ok,'unknown scenario blocked');
S.save(ai.state);
const recoverState=S.load();ok(D.current(recoverState).id==='assistant-sources','demo survives reload');
const result=D.restore(recoverState,storage);
ok(result.ok,'restore previous session');
ok(result.state.case.employee==='Praca użytkownika','previous employee restored');
ok(result.state.meeting.questions==='Moje pytania','previous questions restored');
ok(result.state.observations['komunikacja:0'].note==='Notatki użytkownika','previous observations restored');
ok(!D.current(result.state),'not in demo after restoration');
ok(storage.getItem('kompas-demo-previous-session-v1')===null,'backup removed only after restore');
const failingStorage={getItem:()=>null,setItem:()=>{throw Error('storage disabled')},removeItem:()=>{}};
ok(!D.begin('first-positive',original,failingStorage).ok,'cannot overwrite when backup fails');
console.log(`PASS ${checks} checks: five fixtures, validation, engine calculations, user backup/restore, reload, unsafe storage`);
