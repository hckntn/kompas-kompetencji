'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),storage=new Map(),window={};
const context=vm.createContext({window,Date,console,sessionStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,String(v))}});
for(const f of ['data/competencies.js','data/procedures.js','data/first-rules.js','data/knowledge.js','js/assessment.js','js/validation.js','js/workflow.js','js/session.js','js/engine.js','js/state.js','js/assistant.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),context,{filename:f});
const S=window.KOMPAS_STORE,F=window.KOMPAS_FIRST_RULES,W=window.KOMPAS_WORKFLOW,SS=window.KOMPAS_SESSION,A=window.KOMPAS_ASSESSMENT,V=window.KOMPAS_VALIDATION;
let checks=0;function ok(cond,msg){assert.ok(cond,msg);checks++;}
const state=S.initial();
ok(state.version===3&&!!state.firstFormal,'state v3');
ok(W.getSteps('periodic').length===6&&W.getSteps('first').length===6,'both six-step procedures');
ok(F.IDS.length===5&&F.IDS.every(id=>A.getCompetency(id)),'five legal elements');
ok(!W.canNavigate(state,4).ok,'cannot skip steps');
ok(!V.check(state,['unregistered']).ok,'fail closed');
const first=S.initial();
ok(SS.changeTrack(first,'first').ok,'switch to first');
ok(first.selected.length===5&&F.IDS.every(id=>first.selected.includes(id)),'all five first criteria mandatory');
ok(!SS.toggleCriterion(first,'wiedza').ok,'cannot deselect a mandatory first element');
ok(!W.canNavigate(first,3).ok,'first observations required');
for(const id of F.IDS){const c=A.getCompetency(id);for(let i=0;i<c.indicators.length;i++){ok(SS.rate(first,id,i,3).ok,`${id} observation ${i}`);}}
ok(A.totals(first).allObserved,'all behavioral observations complete');
ok(!SS.gradeFirst(first,'wiedza',4).ok,'only statutory 3/5/7 allowed');
ok(!SS.gradeFirst(first,'analityka',5).ok,'not a first element');
for(const id of F.IDS)ok(SS.gradeFirst(first,id,5).ok,`first grade ${id}`);
ok(F.evaluate(first.firstFormal).average===5,'first mean = 5');
ok(!W.canNavigate(first,4).ok,'formal conditions block navigation');
first.firstFormal.examStatus='passed';first.firstFormal.reportOnTime='yes';first.firstFormal.employmentDate='2026-02-01';first.firstFormal.introMeetingDate='2026-02-10';first.firstFormal.reportDue='2026-10-09';first.firstFormal.assessmentMeetingDate='2026-11-21';
ok(F.evaluate(first.firstFormal).result==='pozytywna','all five positive conditions');
ok(W.canNavigate(first,5).ok,'complete formal first workflow navigable');
ok(SS.finalize(first).ok&&first.finalized,'formal first can finalize');
ok(first.history.every(x=>!JSON.stringify(x).includes(first.case.employee)),'history no personnel');
first.firstFormal.grades.rzetelnosc=3;first.firstFormal.grades.wiedza=3;
let result=F.evaluate(first.firstFormal);
ok(result.result==='negatywna'&&result.lowCount===2,'two lows force negative even when average >=4');
ok(!F.checkFormal(first).ok,'negative requires justification');
first.firstFormal.negativeReason='Udokumentowane niespełnienie oczekiwań.';
ok(F.checkFormal(first).ok,'negative with justification accepted');
first.firstFormal.grades.rzetelnosc=5;first.firstFormal.grades.wiedza=5;
first.firstFormal.reportOnTime='no';ok(F.evaluate(first.firstFormal).result==='negatywna','late report means negative');
first.firstFormal.reportOnTime='yes';first.firstFormal.examStatus='failed';ok(F.evaluate(first.firstFormal).result==='negatywna','exam failed means negative');
first.firstFormal.examStatus='exempt';first.firstFormal.exemptionKind='replacement';
ok(F.evaluate(first.firstFormal).result==='pozytywna','statutory exception can bypass exam');
first.firstFormal.exemptionKind='invalid';ok(!F.checkFormal(first).ok,'invalid exemption rejected');
const periodic=S.initial();S.fillDemo(periodic);
ok(W.canNavigate(periodic,5).ok,'v0.3 periodic demo still passes');
ok(SS.finalize(periodic).ok,'periodic demo finalizes');
ok(A.summaryFor(periodic,'komunikacja').suggestion===3,'original demo heuristic intact');
const migrated=S.initial();migrated.version=2;migrated.case.track='first';migrated.selected=['komunikacja','wspolpraca','organizacja'];migrated.finalized=true;migrated.finalizedAt='2026-11-20';migrated.observations['komunikacja:0']={level:2,note:'Do not delete'};
const m=S.migrate(migrated);
ok(m.version===3&&m.selected.length===5&&m.finalized===false,'v0.3 first migration demotes old finished status');
ok(m.observations['komunikacja:0'].note==='Do not delete','first migration preserves old notes');
const old=S.initial();old.version=1;old.observation={'wspolpraca:1':'legacy note'};delete old.history;
ok(S.migrate(old).observations['wspolpraca:1'].note==='legacy note','v0.2 notes migrated');
S.fillFirstDemo(first);
ok(first.case.track==='first'&&F.evaluate(first.firstFormal).result==='pozytywna','first official positive fixture');
ok(W.canNavigate(first,5).ok&&SS.finalize(first).ok,'first fixture completes');
const assistant=window.KOMPAS_ASSISTANT;
for(const [q,token] of [['Jakie elementy pierwszej oceny?','pięć'],['Jakie oceny 3, 5 i 7?','3 pkt'],['Kiedy pierwsza ocena jest pozytywna?','pozytywna']]){const answer=assistant.offline(q);ok(answer.supported&&answer.sources[0].url?.includes('eli.gov.pl')&&answer.text.includes(token),`legal assistant ${q}`);}
ok(!assistant.offline('Jaki jest dokładny termin odwołania?').supported,'unknown legal question refuses');
for(let i=0;i<150;i++)SS.record(periodic,'step_changed',{stepId:'start'});
ok(periodic.history.length===120,'bounded history');
console.log(`PASS ${checks} checks: formal first assessment, 3/5/7, all positive conditions, exceptions, notes migration, periodic regression, source-linked assistant`);
